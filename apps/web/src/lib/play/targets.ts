const themes: PlayTheme[] = [
  'EVERYDAY',
  'FOOD',
  'TRAVEL',
  'SILLY',
  'GET_TO_KNOW_YOU',
  'AFFECTIONATE',
];

/** Null explicitly means custom targets only, never a silently substituted language. */
export function playTargetSuggestions(
  theme: PlayTheme,
  targetLang: string,
  supportLang: string,
  variation: number
) {
  const targets = words[targetLang];
  if (!targets) return null;
  const offset = themes.indexOf(theme) * 4;
  const ids = ['A', 'B', 'C', 'D'] as const;
  return ids.map((id, index) => {
    const position = offset + ((index + (variation % 4)) % 4);
    return playChoiceSchema.parse({
      id,
      text: targets[position],
      supportText: words[supportLang]?.[position] ?? null,
      symbol: '✦',
    });
  });
}
